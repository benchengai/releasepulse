"""Generate a synthetic feedback set with planted ground truth.

An app spec (see tallynote.py) fixes, per release, how many items mention each
feature with each polarity. Those counts are planted exactly: each mention is
placed in a random item, and the item's text is composed from hand-written
phrases with slots filled at random. Because every mention is a known phrase,
the gold labels record its character span, which the evaluation uses to pair
extracted aspects with planted mentions. Phrases marked with a leading "~" are
hard on purpose (sarcasm, no feature name, negated praise, typos, emoji); their
mentions are flagged `hard` so recall on them can be reported separately.

Everything is seeded, so `releasepulse synth` reproduces the committed files
byte for byte. All texts are fictional and every file says so.
"""

from __future__ import annotations

import csv
import io
import json
import random
from datetime import date, timedelta
from pathlib import Path

from ..ingest import DUPLICATE_JACCARD, DUPLICATE_MIN_TOKENS, _tokens

POLARITY_KEYS = {"negative": "neg", "positive": "pos", "neutral": "req"}
STORE_SOURCES = ("app_store", "play_store")
TICKET_SOURCE = "issue_tracker"
NOTICE = "SYNTHETIC DATA: fictional app, fictional reviews, generated by releasepulse.synthetic for evaluation."

OPENERS = [
    "Updated yesterday.", "Been using this for about a year.", "Honest review:", "Quick review.",
    "I use this every day for work.", "Long time user here.", "Downloaded it last month.",
    "My partner recommended it.", "Edit after the latest update:", "Short version:",
]
TICKET_PREFIXES = ["", "[Bug] ", "Bug: ", "Customer report: "]
TICKET_SUFFIXES = ["", " Reported via support.", " Several users affected.", " Priority: high.", " Logs attached."]
CLOSERS_NEG = ["Please fix.", "Will change my rating when this is sorted.", "Really frustrating.",
               "Hoping for an update soon.", "Not happy right now.", "Fix this please!!"]
CLOSERS_POS = ["Thanks to the devs!", "Keep it up.", "Highly recommend.", "Worth it.", "Five stars from me."]
CLOSERS_ANY = ["That's all.", "Just my two cents.", "Overall it's fine.", "We'll see."]


def _fill(text: str, slots: dict, rng: random.Random) -> str:
    out = text
    for name, options in slots.items():
        while "{" + name + "}" in out:
            out = out.replace("{" + name + "}", rng.choice(options), 1)
    return out


def _version_string(version: str, rng: random.Random) -> str:
    return rng.choice([version, f"{version}.0", f"{version}.0", f"{version}.1", f"{version}.2", f"v{version}"])


def _windows(spec: dict) -> list[tuple[date, date]]:
    rels = spec["releases"]
    out = []
    for i, r in enumerate(rels):
        start = date.fromisoformat(r["date"])
        end = (date.fromisoformat(rels[i + 1]["date"]) - timedelta(days=1)) if i + 1 < len(rels) \
            else start + timedelta(days=spec["last_window_days"])
        out.append((start, end))
    return out


def _random_day(window: tuple[date, date], rng: random.Random) -> date:
    return window[0] + timedelta(days=rng.randint(0, (window[1] - window[0]).days))


def _phrase_pool(feature: dict, polarity: str, ticket: bool) -> list[str]:
    key = ("ticket_" if ticket else "") + POLARITY_KEYS[polarity]
    return feature.get(key, [])


class _Distinct:
    """Keeps texts of different (fictional) people from being near-identical, which
    would make them look like one message posted twice."""

    def __init__(self):
        self.seen: list[set[str]] = []

    def clashes(self, text: str) -> bool:
        if len(text.split()) < DUPLICATE_MIN_TOKENS:
            return False
        toks = _tokens(text)
        return any(len(toks & s) / len(toks | s) >= DUPLICATE_JACCARD for s in self.seen)

    def add(self, text: str) -> None:
        if len(text.split()) >= DUPLICATE_MIN_TOKENS:
            self.seen.append(_tokens(text))


class _Picker:
    """Cycles through a phrase pool in shuffled order so phrases repeat as little as possible."""

    def __init__(self, rng: random.Random):
        self.rng = rng
        self.queues: dict[tuple, list[str]] = {}

    def pick(self, key: tuple, pool: list[str]) -> str:
        queue = self.queues.get(key)
        if not queue:
            queue = pool[:]
            self.rng.shuffle(queue)
            self.queues[key] = queue
        return queue.pop()


def _compose_review(mentions: list[tuple[str, str, str]], rng: random.Random,
                    force_extra: bool = False) -> tuple[str, list[dict]]:
    """mentions: (feature, polarity, phrase). Returns text and gold mention spans.
    `force_extra` always adds an opener or a closer, to make a text distinct."""
    parts: list[str] = []
    spans = []
    extra = rng.choice(["opener", "closer"]) if force_extra else None
    if extra == "opener" or rng.random() < 0.3:
        parts.append(rng.choice(OPENERS))
    previous = None
    for feature, polarity, phrase in mentions:
        if previous is not None:
            mark, body = ("~", phrase[1:]) if phrase.startswith("~") else ("", phrase)
            if previous == "negative" and polarity == "positive":
                parts.append(rng.choice(["On the plus side,", "That said,", "But", "Still,"]))
                phrase = mark + (body[0].lower() + body[1:] if not body[:2].isupper() else body)
            elif rng.random() < 0.35:
                parts.append(rng.choice(["Also", "Also,", "And", "Plus"]))
                phrase = mark + (body[0].lower() + body[1:] if not body[:2].isupper() else body)
        hard = phrase.startswith("~")
        phrase = phrase.removeprefix("~")
        offset = sum(len(p) + 1 for p in parts)
        parts.append(phrase)
        spans.append({"feature": feature, "polarity": polarity, "start": offset, "end": offset + len(phrase),
                      **({"hard": True} if hard else {})})
        previous = polarity
    if extra == "closer" or rng.random() < 0.3:
        pols = {m[1] for m in mentions}
        pool = CLOSERS_NEG if pols == {"negative"} else CLOSERS_POS if pols == {"positive"} else CLOSERS_ANY
        parts.append(rng.choice(pool))
    text = " ".join(parts)
    for s in spans:
        assert text[s["start"]:s["end"]], s
    return text, spans


def _rating(mentions: list[dict], noise_kind: str | None, rng: random.Random) -> int:
    pols = {m["polarity"] for m in mentions}
    if "negative" in pols:
        return rng.choice([1, 1, 2, 2, 3]) if "positive" not in pols else rng.choice([2, 3, 3, 4])
    if "positive" in pols:
        return rng.choice([4, 5, 5, 5])
    if noise_kind == "generic_negative":
        return rng.choice([1, 2, 2, 3])
    if noise_kind == "generic_positive":
        return rng.choice([4, 5, 5])
    return rng.choice([1, 3, 4, 5, 5])


def generate(spec: dict) -> dict:
    rng = random.Random(spec["seed"])
    picker = _Picker(rng)
    distinct = _Distinct()
    features = spec["features"]
    windows = _windows(spec)
    slots = spec["slots"]
    drafts = []

    for ri, release in enumerate(spec["releases"]):
        version = release["version"]
        n = release["volume"]
        sources = [TICKET_SOURCE if rng.random() < spec["ticket_share"] else rng.choice(STORE_SOURCES)
                   for _ in range(n)]
        slots_used: list[list[tuple[str, str]]] = [[] for _ in range(n)]
        planted = []
        for fid, counts in spec["counts"].items():
            for polarity, per_release in counts.items():
                planted += [(fid, polarity)] * per_release[ri]
        rng.shuffle(planted)
        for fid, polarity in planted:
            weights = []
            for i in range(n):
                used = slots_used[i]
                if any(f == fid for f, _ in used):
                    weights.append(0.0)
                elif sources[i] == TICKET_SOURCE:
                    ok = not used and _phrase_pool(features[fid], polarity, ticket=True)
                    weights.append(4.0 if ok else 0.0)  # tickets are nearly always about an issue
                else:
                    weights.append([1.0, 0.35, 0.1, 0.0][min(len(used), 3)])
            if not any(weights):
                raise ValueError(f"no room for {fid} {polarity} in {version}")
            i = rng.choices(range(n), weights)[0]
            slots_used[i].append((fid, polarity))

        for i in range(n):
            ticket = sources[i] == TICKET_SOURCE
            used = slots_used[i]
            noise_kind = None
            if not used:
                kinds = spec["noise_weights"] if not ticket else {"ticket_noise": 1}
                noise_kind = rng.choices(list(kinds), list(kinds.values()))[0]
                for attempt in range(40):
                    if attempt == 20:  # long noise texts used up: fall back to a short one
                        noise_kind = "generic_positive" if not ticket else noise_kind
                    text = _fill(picker.pick(("noise", noise_kind), spec["noise"][noise_kind]), slots, rng)
                    if not distinct.clashes(text):
                        break
                mentions = []
            elif ticket:
                fid, polarity = used[0]
                pool = _phrase_pool(features[fid], polarity, ticket=True)
                base = picker.pick((fid, polarity, "ticket"), pool)
                for attempt in range(40):
                    text = _fill(base, slots, rng).replace("{version_seen}", _version_string(version, rng))
                    if attempt:
                        text = rng.choice(TICKET_PREFIXES) + text + rng.choice(TICKET_SUFFIXES)
                    if not distinct.clashes(text):
                        break
                mentions = [{"feature": fid, "polarity": polarity, "start": 0, "end": len(text)}]
            else:
                for attempt in range(40):
                    if attempt % 10 == 0:
                        chosen = [(fid, pol, _fill(picker.pick((fid, pol), _phrase_pool(features[fid], pol, False)),
                                                   slots, rng)) for fid, pol in used]
                    text, mentions = _compose_review(chosen, rng, force_extra=attempt > 0)
                    if not distinct.clashes(text):
                        break
            if distinct.clashes(text):
                raise ValueError(f"could not make a distinct text for {version} item {i}: {text}")
            distinct.add(text)
            stale = ri + 1 < len(windows) and rng.random() < spec["stale_share"]
            day = _random_day(windows[ri + 1] if stale else windows[ri], rng)
            missing_version = rng.random() < spec["missing_version_share"] and not stale
            drafts.append({
                "release": version, "date": day.isoformat(), "source": sources[i],
                "version": "" if missing_version else _version_string(version, rng),
                "text": text, "mentions": mentions, "noise_kind": noise_kind,
                "rating": None if ticket else _rating(mentions, noise_kind, rng),
            })

    for dup in spec.get("duplicates", []):
        ri = next(i for i, r in enumerate(spec["releases"]) if r["version"] == dup["release"])
        day = _random_day(windows[ri], rng)
        group = []
        for k, (text, source) in enumerate(zip(dup["copies"], dup["sources"])):
            mentions = [{"feature": dup["feature"], "polarity": dup["polarity"], "start": 0, "end": len(text)}]
            group.append({
                "release": dup["release"], "date": (day + timedelta(days=k // 2)).isoformat(), "source": source,
                "version": _version_string(dup["release"], rng), "text": text, "mentions": mentions,
                "noise_kind": None, "rating": None if source == TICKET_SOURCE else 1, "dup_group": dup["id"],
            })
        drafts += group

    drafts.sort(key=lambda d: (d["date"], d["source"], d["text"]))
    prefix = spec["id_prefix"]
    items, gold_items = [], {}
    groups: dict[str, str] = {}
    for k, d in enumerate(drafts, start=1):
        item_id = f"{prefix}-{k:04d}"
        duplicate_of = None
        if g := d.get("dup_group"):
            duplicate_of = groups.get(g)
            groups.setdefault(g, item_id)
        items.append({"id": item_id, "date": d["date"], "version": d["version"], "source": d["source"],
                      "rating": d["rating"] if d["rating"] is not None else "", "text": d["text"]})
        gold_items[item_id] = {"release": d["release"], "mentions": d["mentions"], "noise_kind": d["noise_kind"],
                               "duplicate_of": duplicate_of}

    gold = {
        "notice": NOTICE,
        "app": {k: spec[k] for k in ("id", "name", "product", "description")},
        "releases": [{k: r[k] for k in ("version", "date", "notes")} for r in spec["releases"]],
        "features": {fid: {"name": f["name"], "description": f["description"]} for fid, f in features.items()},
        "counts": spec["counts"],
        **{k: spec["gold"][k] for k in ("regressions", "improvements", "praised", "traps")},
        "items": gold_items,
    }
    return {"items": items, "gold": gold}


def to_csv(rows: list[dict], fields: list[str]) -> str:
    buf = io.StringIO()
    w = csv.DictWriter(buf, fieldnames=fields, lineterminator="\n")
    w.writeheader()
    w.writerows(rows)
    return buf.getvalue()


def write(spec: dict, out_dir: Path) -> dict:
    data = generate(spec)
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "feedback.csv").write_text(
        to_csv(data["items"], ["id", "date", "version", "source", "rating", "text"]), encoding="utf-8")
    (out_dir / "releases.csv").write_text(
        to_csv([{k: r[k] for k in ("version", "date", "notes")} for r in spec["releases"]],
               ["version", "date", "notes"]), encoding="utf-8")
    (out_dir / "gold.json").write_text(json.dumps(data["gold"], indent=1, ensure_ascii=False) + "\n",
                                       encoding="utf-8")
    (out_dir / "README.md").write_text(
        f"# {spec['name']} (synthetic)\n\n{NOTICE}\n\n{spec['description']}\n\n"
        f"- `feedback.csv`: {len(data['items'])} items (app-store reviews and issue tickets)\n"
        f"- `releases.csv`: {len(spec['releases'])} releases with release notes\n"
        f"- `gold.json`: planted mentions with character spans, regressions, improvements, traps\n\n"
        f"Regenerate with `uv run releasepulse synth {spec['id']}`.\n", encoding="utf-8")
    return data
